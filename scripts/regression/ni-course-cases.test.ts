import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import teachingIndex from '../../docs/tianji-ziwei/mobile-index.generated.json';
import { generateChart, resolveEffectiveLunarDate } from '../../lib/ziwei/algorithm';
import { lunarToSolar } from '../../lib/ziwei/lunar-solar';
import { niAnnualBranch, niFortune } from '../../lib/ziwei/ni-school';
import { retrieveTeaching, evidenceWarning } from '../../mobile/deepseek/teaching';
import cases from '../../docs/ni-course-cases.json';

const source = readFileSync(new URL('../../docs/tianji-ziwei/entries.jsonl', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
assert.equal(teachingIndex.sourceSha256, createHash('sha256').update(source).digest('hex'), '教学索引必须对应当前课程原文（统一 LF 换行）');

for (const c of cases) {
  // Inputs transcribed from course case headings; expectations are independently
  // stated in the lecture, not snapshots generated by this implementation.
  const date = lunarToSolar(c.lunar[0], c.lunar[1], c.lunar[2]);
  assert(date, c.id);
  const chart = generateChart({ ...date, hour: c.hour, gender: c.gender as 'male' | 'female' });
  if (c.expected.ming !== null) assert.equal(chart.mingGongBranch, c.expected.ming, `${c.id}: 命宫`);
  for (const [star, branch] of Object.entries(c.expected.stars)) {
    assert.equal(chart.palaces.find(p => p.stars.some(s => s.name === star))?.branch, branch, `${c.id}: ${star}`);
  }
  for (const [age, branch] of c.expected.annual) {
    const f = niFortune(chart, 'liunian', c.lunar[0] + age - 1);
    assert.equal(f.age, age);
    assert.equal(f.annualBranch, branch, `${c.id}: 小流年${age}岁`);
  }
  if (c.id === 'tianji-ziwei-zi') {
    const f = niFortune(chart, 'daxian', 1994);
    assert.deepEqual([f.daXian?.startAge, f.daXian?.endAge, f.activeBranch], [34, 43, 9]);
    assert.equal(niFortune(chart, 'daxian', 1961).daXian, null, '起限前不误套当下大限');
    const evidence = retrieveTeaching({ chart, selectedPalace: chart.palaces.find(p => p.branch === 6)!, view: 'mingpan', liunianYear: 1994 }, '命宫性格');
    assert(evidence.some(e => e.part === 9 && e.time === '00:03:14'), '午宫贪狼须取课程的宫位条件');
    assert.equal(evidenceWarning(`教学依据 [${evidence[0].id}]`, evidence), '');
    assert(evidenceWarning('教学依据 [TJ-9999]', evidence));
    assert(evidenceWarning('无依据自由发挥', evidence));
    assert(evidenceWarning(`倪老师说：“保证你今年必定获得巨额横财。” [${evidence[0].id}]`, evidence));
    assert.equal(evidenceWarning(`教学原话：“${evidence[0].quote}” [${evidence[0].id}]`, evidence), '');
  }
  console.log(`✓ 课程案例 ${c.id}: 命宫、${Object.keys(c.expected.stars).length} 项星位及小流年`);
}

// Course's 闰四月当五月, not a third-party engine's default split policy.
for (const day of [1, 15, 16, 29]) {
  const date = lunarToSolar(2020, 4, day, true)!;
  const e = resolveEffectiveLunarDate(date.year, date.month, date.day);
  assert.equal(e.lunarMonth, 5);
  assert.equal(e.lunarDay, day);
  const a = generateChart({ ...date, hour: 6, gender: 'female' });
  const reference = generateChart({ ...lunarToSolar(2020, 5, day)!, hour: 6, gender: 'female' });
  assert.deepEqual(a.palaces.map(p => [p.branch, p.name, p.stars]), reference.palaces.map(p => [p.branch, p.name, p.stars]));
}
assert.equal(niAnnualBranch(1, 'female', 37), 7);
assert.equal(niAnnualBranch(1, 'female', 40), 4);
assert.equal(niAnnualBranch(1, 'male', 2), 8);
assert.equal(niAnnualBranch(1, 'female', 2), 6);
assert.equal(niAnnualBranch(1, 'female', 0), null);
assert.equal(generateChart({ year: 1952, month: 7, day: 21, hour: 6, gender: 'female' }).lunarInfo.lunarDay, 30);
console.log('✓ 闰月全月归下月、男顺女逆、起限前范围、教学检索及伪造引用拦截通过');
